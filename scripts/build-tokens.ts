/**
 * Generates src/ui/tokens.css from design/tokens.json.
 *
 * design/tokens.json is the only place a colour, type style, spacing step or
 * radius is defined. Tailwind v4 reads the generated @theme block and turns
 * every token into a utility (bg-surface, text-page-title, rounded-lg, p-5).
 * Run by `pnpm tokens`, which `dev`, `build` and `typecheck` all call first.
 *
 * Dark is the only theme, so the tokens land straight on :root via @theme.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = join(import.meta.dirname ?? __dirname, '..');
const source = join(root, 'design', 'tokens.json');
const target = join(root, 'src', 'ui', 'tokens.css');

type ColorToken = { name: string; value: Record<string, string>; usage?: string };
type TypeStyle = {
  name: string;
  fontSize: string;
  lineHeight: string;
  fontWeight: number;
  usage?: string;
};
type TypeGroup = { name: string; family: string; styles: TypeStyle[] };
type NamedToken = { name: string; value: string; usage?: string };

type Tokens = {
  name: string;
  version: number;
  color: { themes: { id: string }[]; tokens: ColorToken[] };
  type: { families: Record<string, string>; groups: TypeGroup[] };
  spacing: { tokens: NamedToken[] };
  radius: { tokens: NamedToken[] };
};

const tokens = JSON.parse(readFileSync(source, 'utf8')) as Tokens;
const THEME = 'dark';

const problems: string[] = [];
const lines: string[] = [];

lines.push(`/* Generated by scripts/build-tokens.ts from design/tokens.json`);
lines.push(` * (${tokens.name} tokens, version ${tokens.version}). Do not edit by hand:`);
lines.push(` * change design/tokens.json and run \`pnpm tokens\`. */`);
lines.push('');
lines.push('@theme {');

lines.push('  /* Colour — dark is the default and only theme. */');
for (const token of tokens.color.tokens) {
  const value = token.value[THEME];
  if (!value) {
    problems.push(`colour token "${token.name}" has no "${THEME}" value`);
    continue;
  }
  lines.push(`  --color-${token.name}: ${value};${token.usage ? ` /* ${token.usage} */` : ''}`);
}

lines.push('');
lines.push('  /* Type families. Geist for text, Geist Mono for money. */');
for (const [key, value] of Object.entries(tokens.type.families)) {
  lines.push(`  --font-${key}: ${value};`);
}

lines.push('');
lines.push('  /* Type styles: size, line height and weight travel together. */');
for (const group of tokens.type.groups) {
  const family = tokens.type.families[group.family];
  if (!family) problems.push(`type group "${group.name}" uses unknown family "${group.family}"`);
  for (const style of group.styles) {
    lines.push(`  --text-${style.name}: ${style.fontSize};`);
    lines.push(`  --text-${style.name}--line-height: ${style.lineHeight};`);
    lines.push(`  --text-${style.name}--font-weight: ${style.fontWeight};`);
    lines.push(`  --text-${style.name}--font-family: var(--font-${group.family});`);
  }
}

lines.push('');
lines.push('  /* Spacing steps (space-1 -> p-1, gap-1, ...). */');
for (const token of tokens.spacing.tokens) {
  const step = token.name.replace(/^space-/, '');
  if (step === token.name) problems.push(`spacing token "${token.name}" is not named space-<n>`);
  lines.push(`  --spacing-${step}: ${token.value};${token.usage ? ` /* ${token.usage} */` : ''}`);
}

lines.push('');
lines.push('  /* Radii (radius-lg -> rounded-lg). */');
for (const token of tokens.radius.tokens) {
  const name = token.name.replace(/^radius-/, '');
  if (name === token.name) problems.push(`radius token "${token.name}" is not named radius-<name>`);
  lines.push(`  --radius-${name}: ${token.value};${token.usage ? ` /* ${token.usage} */` : ''}`);
}

lines.push('}');
lines.push('');

if (problems.length > 0) {
  console.error('design/tokens.json is not usable:');
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, lines.join('\n'), 'utf8');

const counts = [
  `${tokens.color.tokens.length} colours`,
  `${tokens.type.groups.reduce((n, g) => n + g.styles.length, 0)} type styles`,
  `${tokens.spacing.tokens.length} spacing steps`,
  `${tokens.radius.tokens.length} radii`,
].join(', ');
console.log(`tokens: wrote src/ui/tokens.css (${counts})`);
